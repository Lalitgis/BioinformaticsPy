# Example: Hyperparameter Tuning with GridSearchCV
from sklearn.model_selection import GridSearchCV

# Define the parameter grid to search
param_grid = {
    'tfidfvectorizer__ngram_range': [(1, 1), (2, 2), (3, 3)],
    'logisticregression__C': [0.1, 1, 10]
}

# Create a GridSearchCV object
grid_search = GridSearchCV(pipeline, param_grid, cv=3, verbose=1, n_jobs=-1)

# Fit GridSearchCV to the training data
grid_search.fit(train_df['NucleotideSequence'], train_df['GeneType'])

# Print the best parameters and best score
print("Best parameters:", grid_search.best_params_)
