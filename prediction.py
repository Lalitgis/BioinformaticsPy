# Load the datasets from the current directory
train_df = pd.read_csv(f'{path}/train.csv', encoding='ascii')
val_df = pd.read_csv(f'{path}/validation.csv', encoding='ascii')
test_df = pd.read_csv(f'{path}/test.csv', encoding='ascii')

# Display the shapes of the datasets
print('Training data shape:', train_df.shape)
print('Validation data shape:', val_df.shape)
print('Test data shape:', test_df.shape)

print(train_df.head())
